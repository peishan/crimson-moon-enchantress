#!/usr/bin/env python3
"""Rebuild scripts/script.js (the in-game story text) from the author's scripts.
   Sources: docs/GAME_ADAPTATION_SCRIPT.md (comics 001-020), docs/GAME_ADAPTATION_SCRIPT_021-039.md (021-039).
   Chapters 2 and 3 have no script text; they are kept from the existing scripts/script.js (transcribed from the comic pages).
   Chapters 4-6 are the script's comic 002-005 text re-sequenced to the art order (see docs/ART_AUDIT.md).
   Run from the repo root:  python3 tools/build_script.py"""
import re, json
META = ('Production note','Note','Status','Footer','Continuity','Continuity correction','Pen name','Companion file')

def clean(t): return re.sub(r'\s+',' ',t.replace('\\','')).strip()

def parse_lines(txt):
    lines=[]
    for raw in txt.strip().split('\n'):
        raw=raw.strip().rstrip('\\').strip()
        if not raw or raw.startswith('---'): continue
        m=re.match(r'\*\*(.+?):\*\*\s*(.*)',raw)
        if m:
            who,t=m.group(1),clean(m.group(2))
            if who in META: continue
            if who=='Narration': lines.append({'k':'nar','t':t})
            elif who.endswith('(thought)'): lines.append({'k':'thought','w':who.replace(' (thought)',''),'t':t})
            else: lines.append({'k':'say','w':who,'t':t})
        elif raw.startswith('*') and raw.endswith('*') or raw.startswith('**END'):
            continue
        else:
            # continuation of the previous entry (wrapped text) or a plain paragraph
            t=clean(raw.replace('**',''))
            if lines: lines[-1]['t']+=' '+t      # wrapped continuation of the previous entry
            else: lines.append({'k':'plain','t':t})
    return lines

def parse_scenes(rest):
    scenes=[]
    for sc in re.split(r'\n### (?:Scene|Panel) \d+ --- ',rest)[1:]:
        h,txt=sc.split("\n",1); txt=txt.split("\n------")[0]
        lines=[]
        for para in re.split(r'\n\s*\n',txt.strip()):
            lines += [l for l in parse_lines(para)]
        scenes.append({'h':clean(h),'l':lines})
    return scenes

def parse_file(path):
    body=open(path,encoding='utf-8').read().split('## Character reference')[0].split('## End-of-Volume-1')[0]
    out={}
    parts=re.split(r'\n# Comic (?:Chapter )?(\d{3}) --- ',body)[1:]
    for i in range(0,len(parts),2):
        n=int(parts[i]); blk=parts[i+1]; title,rest=blk.split('\n',1)
        scenes=parse_scenes(rest)
        status=re.search(r'\*\*Status:\*\*\s*(.*?)(?:\n\n|\n###|\Z)',rest,re.S)
        out[n]={'title':clean(title),'status':clean(status.group(1)) if status else '','rest':rest,'scenes':scenes}
    return out

old=parse_file('docs/GAME_ADAPTATION_SCRIPT.md')
new=parse_file('docs/GAME_ADAPTATION_SCRIPT_021-039.md')
prev=open('scripts/script.js',encoding='utf-8').read()
prev=json.loads(prev[prev.index('const SCRIPT = ')+len('const SCRIPT = '):prev.rindex(';')])
out={}
out[1]={'title':old[1]['title'],'src':'Script comic 001','scenes':old[1]['scenes']}
out[2]=prev['2']; out[3]=prev['3']
out[4]={'title':'Welcome to Muxue','src':'Script comic 002 text, placed here to match the comic order','scenes':old[2]['scenes']}
out[5]={'title':'The Crimson Fairy','src':'Script comics 003 + 004 text, placed here to match the comic order','scenes':old[3]['scenes']+old[4]['scenes']}
out[6]={'title':'Rage','src':'Script comics 005 + 006 text, placed here to match the comic order','scenes':old[5]['scenes']+old[6]['scenes']}
for n in range(7,21): out[n]={'title':old[n]['title'],'src':'Script comic %03d'%n,'scenes':old[n]['scenes']}
PENDING_NOTE={25:'Reconstruction placeholder: the exact title and scene sequence are unavailable. The party continues from the library into the lower passages toward the frozen maze.'}
for n in range(21,40):
    c=new[n]; sc=c['scenes']
    if not sc:
        body=re.sub(r'\*\*[^*]+:\*\*','',c['rest']); body=clean(body.replace('**',''))
        sc=[{'h':'Script pending','l':[{'k':'plain','t':'The surviving record does not include this chapter\'s approved script.'},{'k':'plain','t':body}]}]
    out[n]={'title':c['title'],'src':'Script comic %03d (%s)'%(n,c['status'][:60]),'scenes':sc,'pending':not c['scenes']}
js=("/* Story text per chapter, in COMIC ORDER (the order of the comic pages).\n"
    "   GENERATED by tools/build_script.py from docs/GAME_ADAPTATION_SCRIPT.md (001-020) and docs/GAME_ADAPTATION_SCRIPT_021-039.md (021-039).\n"
    "   Chapters 2-3 are transcribed from the comic pages; 4-6 are re-sequenced script text (see docs/ART_AUDIT.md).\n"
    "   pending:true = the author's record has no approved script for that chapter yet.\n"
    "   Used as the in-game text reader when a chapter's comic art is not uploaded. */\n"
    "const SCRIPT = "+json.dumps(out,ensure_ascii=False,indent=1)+";\n")
open('scripts/script.js','w',encoding='utf-8').write(js)
print({n:(len(v['scenes']),'PENDING' if v.get('pending') else '') for n,v in out.items() if n>=20})
